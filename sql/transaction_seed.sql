DO $$
DECLARE
    rec           RECORD;
    shop_code     VARCHAR;
    shop_format   VARCHAR;
    shop_num      VARCHAR;
    pos_count     INT;
    csh_count     INT;
    i             INT;
    sn_idx        INT;
    start_dates   DATE[] := ARRAY['2024-01-01','2024-03-15','2024-06-01','2024-09-01','2025-01-01']::DATE[];
BEGIN
    FOR rec IN
        SELECT s.site_unique_code,
               sf.site_format_unique_code AS format
        FROM store.site s
        JOIN store.site_info si ON s.site_unique_code = si.site_unique_code
             AND si.site_status_code = 'ACTIVE'
        JOIN store.site_format sf ON s.site_unique_code = sf.site_unique_code
        ORDER BY s.site_unique_code
    LOOP
        shop_code   := rec.site_unique_code;
        shop_format := rec.format;
        shop_num    := LPAD(SUBSTRING(shop_code FROM 3), 3, '0');

        IF shop_format = 'HIPER' THEN
            pos_count := 20 + floor(random() * 11)::INT;  -- 20-30
            csh_count := 20 + floor(random() * 11)::INT;  -- 20-30
        ELSE
            pos_count := 8 + floor(random() * 3)::INT;    -- 8-10
            csh_count := 8 + floor(random() * 3)::INT;    -- 8-10
        END IF;

        FOR i IN 1..pos_count LOOP
            sn_idx := ((i - 1) % 50) + 1;
            INSERT INTO transaction.pos (pos_id, pos_information_id, shop_id, is_current)
            VALUES (
                'POS-' || shop_num || '-' || LPAD(i::TEXT, 3, '0'),
                'POS-SN-' || LPAD(sn_idx::TEXT, 3, '0'),
                shop_code,
                TRUE
            )
            ON CONFLICT DO NOTHING;
        END LOOP;

        FOR i IN 1..pos_count LOOP
            sn_idx := ((i - 1) % 20) + 1;
            INSERT INTO transaction.printer (printer_id, printer_information_id, shop_id, is_current, created_at)
            VALUES (
                'PRT-' || shop_num || '-' || LPAD(i::TEXT, 3, '0'),
                'PRT-SN-' || LPAD(sn_idx::TEXT, 3, '0'),
                shop_code,
                TRUE,
                start_dates[((i - 1) % 5) + 1]
            )
            ON CONFLICT DO NOTHING;
        END LOOP;

        FOR i IN 1..csh_count LOOP
            INSERT INTO transaction.cashier (cashier_id, location_code, person_id)
            VALUES (
                'CSH-' || shop_num || '-' || LPAD(i::TEXT, 3, '0'),
                shop_code,
                NULL
            )
            ON CONFLICT DO NOTHING;
        END LOOP;

        RAISE NOTICE 'Seeded % (%) — % POS, % printers, % cashiers',
            shop_code, shop_format, pos_count, pos_count, csh_count;
    END LOOP;
END $$;

DO $$
DECLARE
    csh             RECORD;
    matched_person  VARCHAR;
    total           INT := 0;
    linked          INT := 0;
BEGIN
    FOR csh IN
        SELECT c.cashier_id, c.location_code
        FROM transaction.cashier c
        WHERE c.person_id IS NULL
        ORDER BY c.cashier_id
    LOOP
        total := total + 1;

        IF random() > 0.85 THEN
            CONTINUE;
        END IF;

        SELECT cu.person_id INTO matched_person
        FROM client.customer_indicator ci
        JOIN client.customer cu ON cu.person_id = ci.person_id
        JOIN client.address ca ON ca.person_id = cu.person_id
        JOIN store.site_address sa ON sa.site_unique_code = csh.location_code
        WHERE ci.type = 'EMPLOYEE'
          AND ci.is_active = TRUE
          AND LOWER(TRIM(ca.address_city)) = LOWER(TRIM(sa.site_address_city))
          AND NOT EXISTS (
              SELECT 1 FROM transaction.cashier ex
              WHERE ex.person_id = cu.person_id
          )
        ORDER BY random()
        LIMIT 1;

        IF matched_person IS NULL THEN
            SELECT cu.person_id INTO matched_person
            FROM client.customer_indicator ci
            JOIN client.customer cu ON cu.person_id = ci.person_id
            WHERE ci.type = 'EMPLOYEE'
              AND ci.is_active = TRUE
              AND NOT EXISTS (
                  SELECT 1 FROM transaction.cashier ex
                  WHERE ex.person_id = cu.person_id
              )
            ORDER BY random()
            LIMIT 1;
        END IF;

        IF matched_person IS NOT NULL THEN
            UPDATE transaction.cashier
            SET person_id = matched_person,
                updated_at = CURRENT_TIMESTAMP
            WHERE cashier_id = csh.cashier_id;
            linked := linked + 1;
        END IF;
    END LOOP;

    RAISE NOTICE 'Cashier-Employee linking: % / % cashiers linked (target 85%%)', linked, total;
END $$;
